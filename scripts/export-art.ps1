param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$utf8 = New-Object System.Text.UTF8Encoding($false)
$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add('// Generated by scripts/export-art.ps1 from original art/blockbench sources. Do not edit.')
$lines.Add('package com.liamryan.standandhold.client;')
$lines.Add('')
$lines.Add('import net.minecraft.client.model.geom.PartPose;')
$lines.Add('import net.minecraft.client.model.geom.builders.CubeListBuilder;')
$lines.Add('import net.minecraft.client.model.geom.builders.LayerDefinition;')
$lines.Add('import net.minecraft.client.model.geom.builders.MeshDefinition;')
$lines.Add('import net.minecraft.client.model.geom.builders.PartDefinition;')
$lines.Add('')
$lines.Add('public final class HumanNpcMeshes {')
$lines.Add('    private HumanNpcMeshes() { }')
function Number([double]$value) { return $value.ToString('0.####', [Globalization.CultureInfo]::InvariantCulture) + 'F' }
function EmitText($path, $text) {
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $text) { throw "Stale art export: $path. Run scripts/export-art.ps1." }
    } else { [IO.Directory]::CreateDirectory((Split-Path $path -Parent)) | Out-Null; [IO.File]::WriteAllText($path, $text, $utf8) }
}
function EmitBytes($path, [byte[]]$bytes) {
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [Convert]::ToBase64String([IO.File]::ReadAllBytes($path)) -cne [Convert]::ToBase64String($bytes)) { throw "Stale texture: $path" }
    } else { [IO.Directory]::CreateDirectory((Split-Path $path -Parent)) | Out-Null; [IO.File]::WriteAllBytes($path, $bytes) }
}
function ReadTexture($texture, $id, $folder) {
    if ($texture.name -notmatch '^[a-z0-9_]+\.png$' -or $texture.source -notmatch '^data:image/png;base64,([A-Za-z0-9+/=]+)$') { throw "Embedded PNG required: $id" }
    $bytes = [Convert]::FromBase64String($Matches[1])
    if ($bytes.Length -gt 2097152 -or $bytes.Length -lt 24 -or [BitConverter]::ToString($bytes, 0, 8) -ne '89-50-4E-47-0D-0A-1A-0A') { throw "Invalid PNG: $id" }
    $expected = if ($folder -eq 'entity') { 64 } else { 16 }
    $width = $bytes[16] * 16777216 + $bytes[17] * 65536 + $bytes[18] * 256 + $bytes[19]
    $height = $bytes[20] * 16777216 + $bytes[21] * 65536 + $bytes[22] * 256 + $bytes[23]
    if ($width -ne $expected -or $height -ne $expected) { throw "PNG dimensions must be ${expected}x${expected}: $id" }
    EmitBytes (Join-Path $root "src/main/resources/assets/standandhold/textures/$folder/$($texture.name)") $bytes
}
function AddGroup($node, $parent, $parentOrigin, $cubes, $seen, $names, $atlas) {
    if ($node.name -notmatch '^[a-z][a-z0-9_]*$' -or !$names.Add([string]$node.name) -or $names.Count -gt 32) { throw 'Invalid/duplicate model part.' }
    if (@($node.rotation | Where-Object { $_ -ne 0 }).Count -gt 0 -or $node.export -eq $false) { throw 'Only unrotated exported humanoid groups are supported.' }
    $builder = 'CubeListBuilder.create()'
    foreach ($child in $node.children) {
        if ($child -isnot [string]) { continue }
        if (!$cubes.ContainsKey($child) -or !$seen.Add($child)) { throw 'Unknown/repeated cube reference.' }
        $cube = $cubes[$child]
        if ($cube.type -ne 'cube' -or $cube.export -eq $false -or !$cube.box_uv -or $cube.inflate -ne 0 -or @($cube.rotation | Where-Object { $_ -ne 0 }).Count -gt 0) { throw 'Only unrotated, non-inflated box-UV cubes are supported.' }
        foreach ($face in @('north','east','south','west','up','down')) {
            if ($null -eq $cube.faces.$face.texture -or $cube.faces.$face.texture -ne 0) { throw 'Every humanoid box face must use atlas 0.' }
        }
        $size = @(0..2 | ForEach-Object { [double]$cube.to[$_] - [double]$cube.from[$_] })
        foreach ($n in $size) { if ($n -le 0 -or $n -gt 32 -or [Math]::Abs($n - [Math]::Round($n)) -gt 0.00001) { throw 'Cube dimensions must be positive whole pixels <=32.' } }
        foreach ($offset in $cube.uv_offset) { if ([double]$offset -ne [Math]::Truncate([double]$offset)) { throw 'Box-UV offsets must be whole pixels.' } }
        $u = [int]$cube.uv_offset[0]; $v = [int]$cube.uv_offset[1]
        if ($u -lt 0 -or $v -lt 0 -or $u + 2 * ($size[0] + $size[2]) -gt $atlas.width -or $v + $size[2] + $size[1] -gt $atlas.height) { throw 'UV rectangle outside declared atlas.' }
        $x = Number ([double]$cube.from[0] - [double]$node.origin[0])
        $y = Number ([double]$node.origin[1] - [double]$cube.to[1])
        $z = Number ([double]$cube.from[2] - [double]$node.origin[2])
        $builder += ".texOffs($u, $v).mirror($(([bool]$cube.mirror_uv).ToString().ToLowerInvariant())).addBox($x, $y, $z, $(Number $size[0]), $(Number $size[1]), $(Number $size[2])).mirror(false)"
    }
    $dx = Number ([double]$node.origin[0] - [double]$parentOrigin[0])
    $dy = Number ([double]$parentOrigin[1] - [double]$node.origin[1])
    $dz = Number ([double]$node.origin[2] - [double]$parentOrigin[2])
    $lines.Add("        PartDefinition $($node.name) = $parent.addOrReplaceChild(`"$($node.name)`", $builder, PartPose.offset($dx, $dy, $dz));")
    foreach ($child in $node.children) { if ($child -isnot [string]) { AddGroup $child $node.name $node.origin $cubes $seen $names $atlas } }
}
$models = @(Get-ChildItem (Join-Path $root 'art/blockbench') -Filter '*.bbmodel' | Sort-Object Name)
if ($models.Count -eq 0) { throw 'No editable art sources found.' }
foreach ($file in $models) {
    $id = $file.BaseName
    if ($id -notin @('survivor_defender','army_rifleman','field_command_post','research_lab','supply_crate')) { throw "Unknown source id: $id" }
    $model = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($model.meta.model_format -eq 'modded_entity') {
        if ($model.elements.Count -gt 64 -or $model.textures.Count -ne 1 -or $model.resolution.width -ne 64 -or $model.resolution.height -ne 64) { throw 'Humanoid source must have <=64 cubes and one 64x64 texture.' }
        if ($model.textures[0].name -ne "$id.png") { throw 'Humanoid texture name must match its model id.' }
        foreach ($name in @('head','body','right_arm','left_arm','right_leg','left_leg')) {
            if (@($model.outliner | Where-Object { $_.name -eq $name }).Count -ne 1) { throw "Animated part must be at model root: $name" }
        }
        $cubes = @{}
        foreach ($cube in $model.elements) { if ($cubes.ContainsKey($cube.uuid)) { throw 'Duplicate cube UUID.' }; $cubes[$cube.uuid] = $cube }
        $seen = New-Object 'System.Collections.Generic.HashSet[string]'
        $names = New-Object 'System.Collections.Generic.HashSet[string]'
        $hashInput = [Text.Encoding]::UTF8.GetBytes([IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n"))
        $sha = [Security.Cryptography.SHA256]::Create()
        try { $hash = [BitConverter]::ToString($sha.ComputeHash($hashInput)).Replace('-', '').ToLowerInvariant() } finally { $sha.Dispose() }
        $lines.Add("    // Source SHA-256: $hash")
        $lines.Add("    public static LayerDefinition $id() {")
        $lines.Add('        MeshDefinition mesh = new MeshDefinition();')
        $lines.Add('        PartDefinition root = mesh.getRoot();')
        foreach ($node in $model.outliner) { AddGroup $node 'root' @(0,24,0) $cubes $seen $names $model.resolution }
        foreach ($name in @('head','hat','body','right_arm','left_arm','right_leg','left_leg')) { if (!$names.Contains($name)) { throw "Missing animated part: $name" } }
        if ($seen.Count -ne $cubes.Count) { throw 'Unreferenced cube in model.' }
        $head = @($model.outliner | Where-Object { $_.name -eq 'head' })
        if ($head.Count -ne 1 -or @($head[0].children | Where-Object { $_ -isnot [string] -and $_.name -eq 'hat' }).Count -ne 1) { throw 'The pinned HumanoidModel requires head/hat nesting.' }
        $lines.Add('        return LayerDefinition.create(mesh, 64, 64);')
        $lines.Add('    }')
        ReadTexture $model.textures[0] $id 'entity'
    } elseif ($model.meta.model_format -eq 'java_block') {
        if ($id -notin @('field_command_post','research_lab','supply_crate') -or $model.resolution.width -ne 16 -or $model.resolution.height -ne 16 -or $model.elements.Count -ne 1 -or $model.textures.Count -ne 3) { throw 'Only the three original full-cube 16px utility models are supported.' }
        $cube = $model.elements[0]
        if (($cube.from -join ',') -ne '0,0,0' -or ($cube.to -join ',') -ne '16,16,16') { throw 'Utility block geometry must match its unchanged full-cube collision.' }
        if ($cube.type -ne 'cube' -or $cube.export -eq $false -or [double]$cube.inflate -ne 0 -or @($cube.rotation | Where-Object { $null -ne $_ -and $_ -ne 0 }).Count -gt 0) { throw 'Utility cube transforms are unsupported.' }
        $textures = [ordered]@{ particle="standandhold:block/$id" }
        for ($i = 0; $i -lt 3; $i++) {
            $name = @($id, "${id}_side", "${id}_top")[$i]
            if ($model.textures[$i].name -ne "$name.png") { throw 'Unexpected utility texture name/order.' }
            $textures["$i"] = "standandhold:block/$name"
            ReadTexture $model.textures[$i] $id 'block'
        }
        $faces = [ordered]@{}
        foreach ($face in @('north','east','south','west','up','down')) {
            $entry = $cube.faces.$face
            if ($null -eq $entry.texture -or $entry.texture -lt 0 -or $entry.texture -gt 2 -or [double]$entry.rotation -ne 0 -or ($entry.uv -join ',') -ne '0,0,16,16') { throw 'Invalid utility face UV/texture.' }
            $faces[$face] = [ordered]@{ uv=@(0,0,16,16); texture=('#' + $entry.texture); cullface=$face }
        }
        $block = [ordered]@{ parent='minecraft:block/block'; textures=$textures; elements=@([ordered]@{from=@(0,0,0);to=@(16,16,16);faces=$faces}) }
        EmitText (Join-Path $root "src/main/resources/assets/standandhold/models/block/$id.json") (($block | ConvertTo-Json -Depth 16 -Compress) + "`n")
    } else { throw "Unsupported source format: $id" }
}
$lines.Add('}')
EmitText (Join-Path $root 'src/main/java/com/liamryan/standandhold/client/HumanNpcMeshes.java') (($lines -join "`n") + "`n")
Write-Output "Art export checked=$Check; $($models.Count) original source models."
